"""Streamlit dashboard for InsightX descriptive analytics."""
from pathlib import Path
import pandas as pd
import streamlit as st

ROOT = Path(__file__).resolve().parent
RAW = ROOT / "data" / "raw"
st.set_page_config(page_title="InsightX | Customer Analytics", page_icon="📊", layout="wide")
st.title("InsightX — Business & Customer Analytics")
st.caption("Purchase-intent sessions and customer review sentiment are separate datasets.")

sessions_path = RAW / "online_shoppers_intention.csv"
reviews_path = RAW / "womens_ecommerce_reviews.csv"

def load_csv(path):
    return pd.read_csv(path) if path.exists() else None

sessions = load_csv(sessions_path)
reviews = load_csv(reviews_path)

if sessions is None and reviews is None:
    st.info("No local datasets found. Run python data/download_data.py from the project root.")
    st.stop()

tab1, tab2 = st.tabs(["Shopping sessions", "Product reviews"])
with tab1:
    st.subheader("Online shopping purchase-intent sessions")
    if sessions is None:
        st.warning("Download the UCI session dataset to view this section.")
    else:
        revenue_raw = sessions["Revenue"]
        if revenue_raw.dtype == bool:
            revenue = revenue_raw
        elif pd.api.types.is_numeric_dtype(revenue_raw):
            revenue = revenue_raw.astype(int).astype(bool)
        else:
            revenue = revenue_raw.astype(str).str.strip().str.lower().map(
                {"true": True, "false": False, "yes": True, "no": False, "1": True, "0": False}
            )
            if revenue.isna().any():
                st.error("Revenue must contain boolean or Yes/No values.")
                st.stop()
        c1, c2, c3 = st.columns(3)
        c1.metric("Sessions", f"{len(sessions):,}")
        c2.metric("Purchase sessions", f"{int(revenue.sum()):,}")
        c3.metric("Purchase rate", f"{revenue.mean():.1%}")
        st.markdown("#### Purchase rate by visitor type")
        if "VisitorType" in sessions:
            visitor = sessions.assign(Purchased=revenue).groupby("VisitorType")["Purchased"].mean()
            st.bar_chart(visitor)
        st.markdown("#### Sessions by month")
        if "Month" in sessions:
            month = sessions.assign(Purchased=revenue).groupby("Month").agg(
                Sessions=("Revenue", "size"), Purchases=("Purchased", "sum")
            )
            st.bar_chart(month[["Sessions", "Purchases"]])
        with st.expander("Preview session data"):
            st.dataframe(sessions.head(100), use_container_width=True)

with tab2:
    st.subheader("Women's e-commerce clothing reviews")
    if reviews is None:
        st.warning("Download the review dataset to view this section.")
    else:
        reviews = reviews.dropna(subset=["rating"]).copy()
        c1, c2, c3 = st.columns(3)
        c1.metric("Reviews", f"{len(reviews):,}")
        c2.metric("Average rating", f"{reviews['rating'].mean():.2f} / 5")
        c3.metric("Recommended", f"{reviews['recommended_ind'].mean():.1%}" if "recommended_ind" in reviews else "N/A")
        st.markdown("#### Rating distribution")
        st.bar_chart(reviews["rating"].value_counts().sort_index())
        if "department_name" in reviews:
            st.markdown("#### Average rating by department")
            dept = reviews.groupby("department_name")["rating"].mean().sort_values(ascending=False)
            st.bar_chart(dept)
        with st.expander("Preview review data"):
            st.dataframe(reviews[["rating", "title", "review_text"]].head(100), use_container_width=True)

st.divider()
st.caption("The two sources have no shared customer IDs and are not joined at customer level. Dashboard charts are descriptive; model metrics are generated by the training scripts.")
